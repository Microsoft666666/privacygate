ROOT=Path(__file__).resolve().parents[1]

def summarize(cases, detector):
    report=evaluate(cases,detector)
    negatives=[c for c in cases if not c.expected]
    false_positives=sum(bool(detector(c.text,c.sensitive_phrases)) for c in negatives)
    return {k:v for k,v in report.items() if k not in {'cases','errors'}} | {
        'negative_messages':len(negatives),'false_positive_negative_messages':false_positives,
        'negative_fpr':false_positives/len(negatives) if negatives else None,
        'ner_tagged_messages':sum(c.requires_ner for c in cases)}

def latency(fn, length, runs=50):
    text=('Please help edit this garden essay. Contact alex@example.com or 949-555-0134. ' * (length//70+2))[:length]
    for _ in range(5): fn(text)
    durations=[]
    for _ in range(runs):
        start=perf_counter_ns();fn(text);durations.append((perf_counter_ns()-start)/1_000_000)
    return {'characters':length,'runs':runs,'p50_ms':median(durations),'p95_ms':sorted(durations)[math.ceil(.95*runs)-1]}

def table(headers, rows):
    return '\n'.join(['| '+' | '.join(headers)+' |','| '+' | '.join('---' for _ in headers)+' |', *['| '+' | '.join(str(c) for c in row)+' |' for row in rows]])

def number(value): return 'n/a' if value is None else f'{value:.3f}'

def render(data):
    data=json.loads(json.dumps(data,sort_keys=True))
    lines=['# Generated benchmark report','', 'Generated by `python -m benchmarks.report`. Do not hand-edit metrics.',
        '', '## Environment','',f"Run: {data['generated_utc']} · Python {data['environment']['python']} · {data['environment']['machine']} · {data['environment']['system']}",
        '', 'Packages: '+', '.join(f'{k} {v}' for k,v in data['environment']['packages'].items()),
        '', 'NER available: '+str(data['ner_available'])+'. Latency excludes cold model loading and Streamlit/browser overhead.',
        '', '## Overall exact-span results','']
    rows=[]
    for dataset,modes in data['datasets'].items():
        for mode,r in modes.items(): rows.append([dataset,mode,r['messages'],number(r['precision']),number(r['recall']),number(r['f1']),f"{r['false_positive_negative_messages']}/{r['negative_messages']}",number(r['negative_fpr'])])
    lines.append(table(['Dataset','Mode','Messages','Precision','Recall','F1','Flagged negatives','Negative FPR'],rows))
    lines += ['', '## Per-category exact-span results','']
    for dataset,modes in data['datasets'].items():
        lines += [f'### {dataset}','']
        rows=[]
        for mode,r in modes.items():
            for c,m in r['per_category'].items():rows.append([mode,c,m['tp'],m['fp'],m['fn'],number(m['precision']),number(m['recall']),number(m['f1'])])
        lines += [table(['Mode','Category','TP','FP','FN','Precision','Recall','F1'],rows),'']
    lines += ['## Warm detector latency','']
    lines.append(table(['Mode','Characters','Runs','p50 ms','p95 ms'],[[mode,r['characters'],r['runs'],number(r['p50_ms']),number(r['p95_ms'])] for mode,rows in data['latency'].items() for r in rows]))
    lines += ['', 'The target is p95 below 300 ms for 2,000 characters; this local measurement is not a CI or hosted-memory guarantee.', '', '## AI4Privacy external benchmark','']
    external=data.get('external')
    if external:
        lines += [f"Synthetic English validation sample: {external['sample_n']} rows; fixed seed {external['seed']}; dataset fingerprint `{external['dataset_fingerprint']}`.",'']
        rows=[]
        for mode,r in external['modes'].items():
            for scoring in ('exact','overlap'):
                m=r[scoring];rows.append([mode,scoring,m['tp'],m['fp'],m['fn'],number(m['precision']),number(m['recall']),number(m['f1'])])
        lines += [table(['Mode','Scoring','TP','FP','FN','Precision','Recall','F1'],rows),'']
        for mode,r in external['modes'].items():
            lines += [f'### External per-category: {mode}','']
            rows=[]
            for scoring in ('exact','overlap'):
                for c,m in r[scoring]['per_category'].items():rows.append([scoring,c,m['tp'],m['fp'],m['fn'],number(m['precision']),number(m['recall']),number(m['f1'])])
            lines += [table(['Scoring','Category','TP','FP','FN','Precision','Recall','F1'],rows),'']
        first=next(iter(external['modes'].values()))
        lines += ['Not-covered annotation counts: '+', '.join(f'{k}: {v}' for k,v in first['not_covered'].items())+'.', '',
                  'External negative FPR: '+', '.join(f"{mode}: {number(r['negative_fpr'])} ({r['negative_messages']} unannotated messages)" for mode,r in external['modes'].items())+'.','']
    else:
        lines += ['External results unavailable; no external accuracy claim is made. Run `python -m benchmarks.ai4privacy_eval --n 1000` and regenerate this report.','']
    lines += ['Acknowledgment: AI4Privacy’s [synthetic dataset](https://huggingface.co/datasets/ai4privacy/pii-masking-300k) is used only for academic/non-commercial evaluation. Its [license](https://huggingface.co/datasets/ai4privacy/pii-masking-300k/blob/main/LICENSE.md) requires written permission for redistribution or derivative dissemination. No rows, samples, or derived row files are committed.', '',
      '## Caveats','',
      '- Hand-authored cases are small, synthetic, and not representative of real users. They are regression evidence, not a real-world accuracy estimate.',
      '- The original and adversarial annotations stay frozen. New model categories can count as false positives where old annotations intentionally omitted them. Realistic NER annotations remain in truth in regex-only mode, so missed names are counted.',
      '- A true positive requires the same category and exact boundaries. Precision/recall/F1 are zero when their denominator is zero. The external overlap score uses maximum one-to-one same-category matching.',
      '- External TEL pools both phone categories into US_PHONE for scoring. Source surnames, streets, and geopolitical labels do not align perfectly with whole-name/street-address/model spans. Unmapped labels are reported separately; unmatched predictions still count as false positives. Do not read this as universal PII coverage.',
      '- Checksums verify format, not identity. Model errors, nicknames, multilingual prose, personal stories, and images can be missed. No detection result guarantees privacy.',
      '- These measurements exercise Python detectors, not the extension’s send interception. Site adapters need live manual QA; the browser uses shape-only phone rules and has no NER.',
      '', 'See [methodology](evaluation.md) and [reproduction commands](VERIFICATION.md).','']
    return '\n'.join(lines)

def main():
    available=ner_status()[0]=='available'
    modes={'v2':previous_detector,'regex':partial(detect,ner=False)}
    if available:modes['ner']=partial(detect,ner=True)
    data={'generated_utc':datetime.now(timezone.utc).isoformat(),
          'environment':{'python':platform.python_version(),'machine':platform.machine(),
                         'system':platform.system(),'packages':{p:version(p) for p in ['presidio-analyzer','spacy','en_core_web_sm','phonenumbers']}},
          'ner_available':available,
          'datasets':{name:{mode:summarize(cases,fn) for mode,fn in modes.items()} for name,cases in [('Original 37',DATASET),('Adversarial 52',ADVERSARIAL),('Realistic 60',REALISTIC)]},
          'latency':{mode:[latency(fn,size) for size in (500,2000)] for mode,fn in modes.items() if mode!='v2'}}
    if available and ner_status()[0]!='available': raise RuntimeError('NER failed during benchmark; refusing to label regex results as NER')
    external=ROOT/'docs/ai4privacy_metrics.json'
    if external.exists():data['external']=json.loads(external.read_text())
    (ROOT/'docs/benchmark_metrics.json').write_text(json.dumps(data,indent=2,sort_keys=True)+'\n')
    (ROOT/'docs/benchmark.md').write_text(render(data))
    print('Generated aggregate benchmark report.')

if __name__=='__main__':main()
